import { writeFileSync } from 'node:fs'
import { basicSources, youtubeBasicMaterials, youtubeAssessment } from '../content/basic-youtube.js'

const questions = Object.entries(youtubeAssessment).flatMap(([grade, aspects]) => Object.entries(aspects).flatMap(([aspect, items]) => items.map((item, i) => {
 const { correct, ...body } = item
 const slot = ['first', 'advanced', 'remedial'][i]
 return { logicalKey: `assessment-${grade.toLowerCase()}-${aspect}-${slot}`, grade, aspect, slot, ...body, answer: correct, data: { visual: body.visual, sourceVideoId: basicSources[grade].videoId, basicSlug: `basic-${grade.toLowerCase()}-${aspect}`, contentRelease: 'basic-youtube-2026-10' } }
})))
if (youtubeBasicMaterials.length !== 12 || questions.length !== 36) throw new Error('Incomplete grade/aspect content')
for (const q of questions) if (!Number.isInteger(q.answer) || !q.options[q.answer]) throw new Error('Invalid answer: ' + q.logicalKey)
const literal = value => `'${JSON.stringify(value, null, 2).replaceAll("'", "''")}'::jsonb`
const output = `-- Generated by scripts/generate-basic-youtube.mjs from content/basic-youtube.js.
-- Run after 004/004b/005. Atomic and safe to run again.
-- Publishes new revisions; historical attempts, answers and keys are retained.
begin;
create table if not exists private.content_releases (
 name text primary key, applied_at timestamptz not null default now()
);
revoke all on private.content_releases from public,anon,authenticated;
do $release$
declare
 materials jsonb := ${literal(youtubeBasicMaterials)};
 bank jsonb := ${literal(questions)};
 item jsonb; new_id uuid; next_revision integer;
begin
 perform pg_advisory_xact_lock(hashtext('basic-youtube-2026-10'));
 if exists(select 1 from private.content_releases where name='basic-youtube-2026-10') then return; end if;
 -- Retire the four generic cards only; leave custom admin content alone.
 update public.lessons set status='archived' where kind='basic' and status='published'
  and slug in ('basic-kosakata','basic-kalimat','basic-bacaan','basic-akademik');
 for item in select jsonb_array_elements(materials) loop
  select coalesce(max(revision),0)+1 into next_revision from public.lessons where slug=item->>'slug';
  update public.lessons set status='archived' where slug=item->>'slug' and status='published';
  insert into public.lessons(slug,revision,kind,grade,aspect,title,data,status)
   values(item->>'slug',next_revision,'basic','ALL',item->>'aspect',item->>'title',item->'data','published');
 end loop;
 for item in select jsonb_array_elements(bank) loop
  select coalesce(max(revision),0)+1 into next_revision from public.questions where logical_key=item->>'logicalKey';
  update public.questions set status='archived' where logical_key=item->>'logicalKey' and kind='assessment' and status='published';
  insert into public.questions(logical_key,revision,kind,grade,aspect,slot,format,prompt,options,data,status)
   values(item->>'logicalKey',next_revision,'assessment',item->>'grade',item->>'aspect',item->>'slot','choice',item->>'prompt',item->'options',item->'data','published') returning id into new_id;
  insert into private.answer_keys(question_id,answer) values(new_id,item->'answer');
 end loop;
 insert into private.content_releases(name) values('basic-youtube-2026-10');
end;
$release$;
commit;
`
writeFileSync(new URL('../supabase/migrations/008_basic_youtube.sql', import.meta.url), output)
console.log('Prepared 008: 12 grade-specific basic materials and 36 assessment questions; keys stay private.')
