import {writeFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
import {expandedLessons} from '../content/expanded-lessons.js'
const uuid=value=>{const h=createHash('sha256').update(value).digest('hex').slice(0,32);return `${h.slice(0,8)}-${h.slice(8,12)}-4${h.slice(13,16)}-8${h.slice(17,20)}-${h.slice(20)}`}
const payload=expandedLessons.map(({id:slug,grade,aspect,title,practice,quiz,...data})=>({id:uuid(slug),slug,grade,aspect,title,data,questions:[practice,...quiz].map((q,i)=>({id:uuid(slug+':question:'+i),logicalKey:slug+':'+i,kind:i?'quiz':'practice',position:i?i-1:0,prompt:q.prompt,options:q.options,answer:q.correct}))}))
if(payload.length!==24||new Set(payload.map(l=>l.slug)).size!==24)throw Error('Expected 24 unique lessons')
for(const l of payload)for(const q of l.questions)if(!Number.isInteger(q.answer)||!q.options[q.answer]||new Set(q.options).size!==3)throw Error('Invalid question '+q.logicalKey)
const literal="'"+JSON.stringify(payload).replaceAll("'","''")+"'::jsonb"
writeFileSync('supabase/migrations/011_expanded_lessons.sql',`-- Generated by scripts/generate-expanded-lessons.mjs; run after 004/004b/005.
-- Adds 24 lessons and 144 questions. Existing content and progress remain intact.
begin;
do $release$
declare items jsonb := ${literal}; item jsonb; q jsonb;
begin
 perform pg_advisory_xact_lock(hashtext('expanded-lessons-2026-10'));
 for item in select jsonb_array_elements(items) loop
  -- A rerun must never overwrite an admin's edited revision or add mixed question sets.
  if exists(select 1 from public.lessons where slug=item->>'slug') then continue; end if;
  insert into public.lessons(id,slug,revision,kind,grade,aspect,title,data,status)
   values((item->>'id')::uuid,item->>'slug',1,'lesson',item->>'grade',item->>'aspect',item->>'title',item->'data','published');
  for q in select jsonb_array_elements(item->'questions') loop
   insert into public.questions(id,logical_key,revision,kind,lesson_id,grade,aspect,position,format,prompt,options,data,status)
    values((q->>'id')::uuid,q->>'logicalKey',1,q->>'kind',(item->>'id')::uuid,item->>'grade',item->>'aspect',(q->>'position')::integer,'choice',q->>'prompt',q->'options','{}'::jsonb,'published');
   insert into private.answer_keys(question_id,answer) values((q->>'id')::uuid,q->'answer');
  end loop;
 end loop;
end; $release$;
commit;
`)
console.log('Prepared 24 additional lessons, 24 practices and 120 evaluation questions: supabase/migrations/011_expanded_lessons.sql')
